export const editorThemeName = (theme) => `nova-${theme}`

export function defineEditorTheme(theme) {
  const palette = EDITOR_THEMES[theme] || EDITOR_THEMES.nova
  const name = editorThemeName(theme)
  const light = theme.startsWith('light-')

  monaco.editor.defineTheme(name, {
    base: light ? 'vs' : 'vs-dark',
    inherit: true,
    rules: light ? LIGHT_RULES : DARK_RULES,
    colors: {
      'editor.background': `#${palette.background}`,
      'editor.foreground': light ? '#1E293B' : '#D6DCE7',
      'editor.lineHighlightBackground': `#${palette.lineHighlight}`,
      'editor.lineHighlightBorder': '#00000000',
      'editorLineNumber.foreground': `#${palette.lineNumber}`,
      'editorLineNumber.activeForeground': `#${palette.lineNumberActive}`,
      'editorCursor.foreground': `#${palette.accent}`,
      'editor.selectionBackground': `#${palette.selection}`,
      'editor.inactiveSelectionBackground': `#${palette.inactiveSelection}`,
      'editor.selectionHighlightBackground': `#${palette.selection}55`,
      'editorIndentGuide.background': `#${palette.indentGuide}`,
      'editorIndentGuide.activeBackground': `#${palette.indentGuideActive}`,
      'editorBracketMatch.background': `#${palette.selection}66`,
      'editorBracketMatch.border': `#${palette.accent}66`,
      'editorGutter.background': `#${palette.background}`,
      'editorWidget.background': `#${palette.widget}`,
      'editorWidget.border': `#${palette.widgetBorder}`,
      'input.background': `#${palette.input}`,
      'input.border': `#${palette.widgetBorder}`,
      focusBorder: `#${palette.accent}66`,
      'list.hoverBackground': `#${palette.lineHighlight}`,
      'scrollbarSlider.background': `#${palette.widgetBorder}66`,
      'scrollbarSlider.hoverBackground': `#${palette.widgetBorder}AA`,
      'scrollbarSlider.activeBackground': `#${palette.widgetBorder}`,
    },
  })

  return name
}

Object.keys(EDITOR_THEMES).forEach(defineEditorTheme)

